
CREATE TYPE relation_t AS ENUM ('Friends', 'Pending', 'Blocked');
CREATE TYPE privilege_t AS ENUM ('Proprietor', 'Consumer');
CREATE TYPE rank_t AS ENUM ('Owner', 'Admin', 'User');

CREATE TABLE "users" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "nicname" text NOT NULL,
  "prv" privilege_t NOT NULL,
  "username" text NOT NULL UNIQUE,
  "password" text NOT NULL,
  "pfp" uuid
);

CREATE TABLE "relations" (
  "relating_user" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "related_user" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "state" relation_t NOT NULL,
  PRIMARY KEY (relating_user, related_user),
  CONSTRAINT friend_equaltiy CHECK (relating_user != related_user)
);


CREATE TABLE "groups" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "name" text NOT NULL,
  "is_dm" bool NOT NULL,
  "gp" uuid
);

CREATE TABLE "group_members" (
  "group_id" uuid NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
  "member_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, member_id)
);

CREATE TABLE "messages" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "message" text,
  "group_id" uuid NOT NULL,
  "user_id" uuid
);

CREATE TABLE "objects" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "hash" char(64) NOT NULL UNIQUE,
  "rel_path" text NOT NULL UNIQUE,
  "mime_type" text NOT NULL,
  "size_bytes" bigint NOT NULL,
  "creation_timestamp" bigint NOT NULL
);

CREATE TABLE "message_objects" (
  "message_id" integer NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  "object_id" uuid NOT NULL REFERENCES objects(id) ON DELETE CASCADE,
  PRIMARY KEY (message_id, object_id)
);

ALTER TABLE "messages" ADD CONSTRAINT "user_msg" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "messages" ADD CONSTRAINT "group_msg" FOREIGN KEY ("group_id") REFERENCES "groups" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "users" ADD CONSTRAINT "pfp_link" FOREIGN KEY ("pfp") REFERENCES "objects" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "groups" ADD CONSTRAINT "gp_link" FOREIGN KEY ("gp") REFERENCES "objects" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

CREATE OR REPLACE FUNCTION enforce_dm() RETURNS trigger AS $$
DECLARE
    is_dm_group boolean;
    member_count int;
BEGIN
    SELECT is_dm INTO is_dm_group FROM groups WHERE id = NEW.group_id;

    IF is_dm_group THEN
        SELECT count(*) INTO member_count FROM group_members
        WHERE group_id = NEW.group_id;

        IF member_count >= 2 THEN
            RAISE EXCEPTION 'DM groups cannot have more than 2 members';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_dm_compliance
BEFORE INSERT ON group_members
FOR EACH ROW EXECUTE FUNCTION enforce_dm();
