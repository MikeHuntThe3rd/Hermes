CREATE TYPE relation_t AS ENUM ('Friends', 'Pending', 'Blocked');
CREATE TYPE privilege_t AS ENUM ('Consumer', 'Proprietor');
CREATE TYPE rank_t AS ENUM ('User', 'Admin', 'Owner');
CREATE TYPE channel_t AS ENUM ('Text', 'Voice');

CREATE TABLE "users" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "nickname" text NOT NULL,
  "prv" privilege_t NOT NULL,
  "username" text NOT NULL UNIQUE,
  "password" text NOT NULL,
  "pfp" uuid
);

CREATE TABLE "relations" (
  "relating_user" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "related_user" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "state" relation_t NOT NULL,
  PRIMARY KEY (relating_user, related_user),
  CONSTRAINT friend_equality CHECK (relating_user != related_user)
);

CREATE TABLE "guilds" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "name" text NOT NULL,
  "gp" uuid
);

CREATE TABLE "channels" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "guild_id" uuid NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  "name" text NOT NULL,
  "category" channel_t NOT NULL
);

CREATE TABLE "dms" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "user_a" uuid REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  "user_b" uuid REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dm_distinct_users CHECK (user_a IS DISTINCT FROM user_b),
  CONSTRAINT dm_ordered CHECK (user_a < user_b),
  UNIQUE (user_a, user_b)
);

CREATE TABLE "guild_invites" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "guild_id" uuid NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  "recipient" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "rank" rank_t NOT NULL,
  UNIQUE (guild_id, recipient)
);

CREATE TABLE "dm_invites" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "dm_id" uuid NOT NULL REFERENCES dms(id) ON DELETE CASCADE,
  "recipient" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  UNIQUE (dm_id, recipient)
);

CREATE TABLE "guild_members" (
  "guild_id" uuid NOT NULL REFERENCES guilds(id) ON DELETE CASCADE,
  "member_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "rank" rank_t NOT NULL,
  PRIMARY KEY (guild_id, member_id)
);

CREATE TABLE "dm_messages" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "dm_id" uuid NOT NULL REFERENCES dms(id) ON DELETE CASCADE,
  "message" text,
  "user_id" uuid REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE "guild_messages" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "channel_id" uuid NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  "message" text,
  "user_id" uuid REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE "objects" (
  "id" uuid PRIMARY KEY DEFAULT uuidv7(),
  "hash" char(64) NOT NULL UNIQUE,
  "rel_path" text NOT NULL UNIQUE,
  "mime_type" text NOT NULL,
  "size_bytes" bigint NOT NULL,
  "creation_timestamp" bigint NOT NULL,
  CHECK (size_bytes >= 0)
);

CREATE TABLE "dm_message_objects" (
  "message_id" bigint NOT NULL REFERENCES dm_messages(id) ON DELETE CASCADE,
  "object_id"  uuid   NOT NULL REFERENCES objects(id)     ON DELETE CASCADE,
  PRIMARY KEY (message_id, object_id)
);

CREATE TABLE "guild_message_objects" (
  "message_id" bigint NOT NULL REFERENCES guild_messages(id) ON DELETE CASCADE,
  "object_id"  uuid   NOT NULL REFERENCES objects(id)        ON DELETE CASCADE,
  PRIMARY KEY (message_id, object_id)
);

ALTER TABLE "users" ADD CONSTRAINT "pfp_link" FOREIGN KEY ("pfp") REFERENCES "objects" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "guilds" ADD CONSTRAINT "gp_link" FOREIGN KEY ("gp") REFERENCES "objects" ("id") ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

CREATE OR REPLACE FUNCTION dm_cleanup() RETURNS trigger AS $$
BEGIN
    DELETE FROM dms WHERE dms.id = OLD.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_dm_state
BEFORE UPDATE OF user_a, user_b ON dms
FOR EACH ROW
WHEN (NEW.user_a IS NULL AND NEW.user_b IS NULL)
EXECUTE FUNCTION dm_cleanup();
